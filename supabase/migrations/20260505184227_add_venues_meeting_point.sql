-- =============================================================================
-- venues.meeting_point 列追加 (Issue #90 動作確認時の追加要件)
-- =============================================================================
-- 背景:
--   会員サイトのイベント詳細画面で「会場住所」を表示していたが、住所そのものは
--   一般会員の予約判断に直接寄与しない情報のため廃止。代わりに「集合場所」を
--   表示する方針に変更 (PR #202 動作確認フィードバック)。
--
--   集合場所はマスタとして会場ごとに保管する (アプリ層ハードコード回避)。
--
-- 変更:
--   1. venues に `meeting_point` text NOT NULL default '現地集合' を追加
--   2. 有明会場のみ '有明テニスの森駅' に UPDATE
--   その他の会場 (亀戸 / 東砂 / 深川 / 深川北) は default の '現地集合' のまま
--
-- 関連:
--   supabase/migrations/20260428143738_db_schema_foundation.sql L78-115 (元 seed)
--   PR #202 (Issue #90) 動作確認フィードバック
--   docs/04-システム設計/01-DB設計/01-論理設計/論理設計.md (venues セクション)
-- =============================================================================

alter table public.venues
  add column if not exists meeting_point text not null default '現地集合';

update public.venues
set meeting_point = '有明テニスの森駅'
where name = '有明会場';
